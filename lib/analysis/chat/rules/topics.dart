/// 주제로 칠 최소 메시지 수 (한 번 나온 건 우연일 수 있음)
const minTopicMessages = 2;

/// 메시지 글자들(normalize의 compact) → 자주 나온 주제 (많은 순, 같으면 위 표 순서, 최대 max개)
List<Topic> detectTopics(Iterable<String> compactTexts, {int max = 3}) {
  final counts = <Topic, int>{};
  for (final c in compactTexts) {
    for (final topic in Topic.values) {
      if (_patterns[topic]!.hasMatch(c)) counts[topic] = (counts[topic] ?? 0) + 1;
    }
  }
  final found = [
    for (final e in counts.entries)
      if (e.value >= minTopicMessages) e,
  ]..sort((a, b) => b.value != a.value
      ? b.value.compareTo(a.value)
      : a.key.index.compareTo(b.key.index));
  return [for (final e in found.take(max)) e.key];
}

final _patterns = {
  for (final topic in Topic.values) topic: RegExp(topic.words.join('|')),
};
