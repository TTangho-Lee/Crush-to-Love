// ---------- 고르기 ----------

/// 방향 설명 하나 고르기 (seed: 0 이상, 대화마다 다른 설명)
String pickHint(Approach approach, {required int seed}) {
  final hints = approachHints[approach] ?? const <String>[];
  return hints.isEmpty ? '' : hints[seed % hints.length];
}

/// 지금 시각에 맞는 멘트 전체 (주제 멘트, 방향 멘트), 주제 멘트 종류가 없거나 주제가 없으면 주제 멘트는 빈 목록
/// formal: 존댓말 멘트 · 존댓말 주제 멘트만
(List<Line>, List<Line>) linePools(
  Approach approach, {
  required DateTime now,
  Topic? topic,
  bool formal = false,
}) {
  final kind = approach.topicKind;
  final topicPool = topic == null || kind == null
      ? const <Line>[]
      : [
          for (final line
              in (formal ? formalTopicLines : topicLines)[topic]?.of(kind) ??
                  const <Line>[])
            if (line.fits(now)) line,
        ];
  final generic = [
    for (final line in (formal ? formalLines : approachLines)[approach] ??
        const <Line>[])
      if (line.fits(now)) line,
  ];
  return (topicPool, generic);
}

/// 예시 멘트 고르기 (최대 count개, 겹치지 않게)
///   formal: 내가 존댓말을 쓰는 사이면 true → 존댓말 멘트 · 존댓말 주제 멘트만
///   topic: 자주 나온 주제가 있고 방향에 주제 멘트 종류가 있으면 첫 줄은 주제 멘트
///   now: 시간대 · 요일에 맞는 멘트만, seed: 0 이상, 대화마다 다른 멘트가 나오게
List<String> pickLines(
  Approach approach, {
  required DateTime now,
  required int seed,
  Topic? topic,
  bool formal = false,
  int count = 3,
}) {
  final kind = approach.topicKind;
  final topicPool = topic == null || kind == null
      ? const <String>[]
      : [
          for (final line
              in (formal ? formalTopicLines : topicLines)[topic]?.of(kind) ??
                  const <Line>[])
            if (line.fits(now)) line.text,
        ];
  final generic = [
    for (final line in (formal ? formalLines : approachLines)[approach] ??
        const <Line>[])
      if (line.fits(now)) line.text,
  ];
  final candidates = <String>{
    if (topicPool.isNotEmpty) topicPool[seed % topicPool.length],
    for (var i = 0; i < generic.length; i++)
      generic[(seed + i) % generic.length],
  };
  return candidates.take(count).toList();
}
