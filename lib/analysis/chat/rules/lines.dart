import 'topics.dart';

/// 시간대
enum TimeSlot {
  /// 5시 ~ 11시
  morning,

  /// 11시 ~ 17시
  day,

  /// 17시 ~ 23시
  evening,

  /// 23시 ~ 5시
  night;

  static TimeSlot of(DateTime t) => switch (t.hour) {
        >= 5 && < 11 => morning,
        >= 11 && < 17 => day,
        >= 17 && < 23 => evening,
        _ => night,
      };
}

/// 예시 멘트 한 줄
class Line {
  const Line(this.text, {this.slot, this.weekend});

  final String text;

  /// 이 시간대에만, 비우면 언제나
  final TimeSlot? slot;

  /// true면 목 ~ 일요일(주말 앞뒤)에만, false면 월 ~ 수요일에만, 비우면 언제나
  final bool? weekend;

  bool fits(DateTime now) {
    final s = slot;
    if (s != null && TimeSlot.of(now) != s) return false;
    final w = weekend;
    if (w != null && (now.weekday >= DateTime.thursday) != w) return false;
    return true;
  }
}

/// 주제 멘트 종류
enum TopicKind {
  /// 가볍게 말 걸기
  open,

  /// 더 물어보기
  ask,

  /// 같이 하자고 제안하기
  invite,
}

/// 주제 하나의 멘트
class TopicLines {
  const TopicLines({required this.open, required this.ask, required this.invite});

  final List<Line> open;
  final List<Line> ask;
  final List<Line> invite;

  List<Line> of(TopicKind kind) => switch (kind) {
        TopicKind.open => open,
        TopicKind.ask => ask,
        TopicKind.invite => invite,
      };
}

